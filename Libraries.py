# Importing the required libraries

import random      # Used to generate random numbers
import math        # Used to perform mathematical operations
import datetime    # Used to work with date and time
# RANDOM LIBRARY
# Generate a random number between 1 and 100
random_number = random.randint(1, 100)

print("Random Number:", random_number)
# MATH LIBRAR

# Find the square root of a number
number = 64
square_root = math.sqrt(number)

print("Square Root of", number, "=", square_root)
# Calculate power (5 raised to power 3)
power_value = math.pow(5, 3)

print("5 raised to the power 3 =", power_value)
# DATETIME LIBRARY


# Display current date and time
current_datetime = datetime.datetime.now()

print("Current Date and Time:", current_datetime)